-- Top 10 Highest Paying Customer

with max_pay as (select customer_id,
                        sum(amount) as "total_pay",
                        dense_rank() over(order by sum(amount)desc ) as rank
                 from payment
                 group by customer_id)

select customer.first_name || ' ' || customer.last_name , max_pay.total_pay
from customer
join max_pay
using(customer_id)
where max_pay.rank<=10
order by rank;


