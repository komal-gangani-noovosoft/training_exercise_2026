-- 4. Find the customers whose total spending is greater than average spending of customers who made at least one payment.
with avg_spending as (
    select avg("Total Spent") as "Avg Spent"
    from(
        select
               sum(payment.amount) as "Total Spent"
        from payment
        group by customer_id
    ) as "total_spent"
)

select customer.first_name || ' ' || customer.last_name as "customer name",
       sum(payment.amount) as "Total Spent"
from payment
         join customer using (customer_id)
group by customer.first_name, customer.last_name
having sum(payment.amount)>(select "Avg Spent" from avg_spending)
order by "Total Spent" desc ;

-- 5. Rank all customers based on they spent.
select customer.first_name || ' ' || customer.last_name as "customer name",
       sum(payment.amount) as "Total Spent",
       dense_rank() over(order by count(payment.amount) ) as rank
from payment
     join customer using (customer_id)
group by customer.first_name, customer.last_name
order by rank;

-- 6. Total revenue of each month.
select extract(MONTH from payment.payment_date) as month,
       sum(payment.amount) as total_revenue
from payment
group by extract(MONTH from payment.payment_date)
order by month;

-- 7. Top 3 customers in each country who spent most.
with cust_spending as(
    select
        first_name || ' ' || last_name as name,
        country.country,
        dense_rank() over(partition by country.country order by sum(amount) desc) as rank
        from payment
        join customer using (customer_id)
        join address using (address_id)
        join city using (city_id)
        join country using (country_id)
    group by first_name, last_name, country.country
)

select name, country, rank
from cust_spending
where rank<=3
order by country,rank;

-- 8. Actors who appear together more than 5 time.

select actor1.first_name || ' ' || actor1.last_name,
       actor2.first_name || ' ' || actor2.last_name,
       count(fa1.film_id) as movie
from actor as actor1
         join film_actor as fa1
              on actor1.actor_id = fa1.actor_id
         join film_actor as fa2
              on fa1.film_id = fa2.film_id and actor1.actor_id < fa2.actor_id
         join actor as actor2
              on fa2.actor_id = actor2.actor_id
group by actor1.first_name, actor1.last_name, actor2.first_name, actor2.last_name
having count(fa1.film_id)>=5
order by movie desc;

-- 9. Actors who appeared in more than 20 films.
select first_name || ' ' || last_name as name,
       count(film_id) as "Film Count"
from actor
join film_actor using (actor_id)
join film using (film_id)
group by first_name || ' ' || last_name
having count(film_id)>20
order by "Film Count" desc;


