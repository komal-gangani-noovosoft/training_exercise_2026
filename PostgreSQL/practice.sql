-- Highest rental cities per country

with city_rentals as (
    select
        co.country,
        ci.city,
        count(r.rental_id) as rentals,
        dense_rank() over(partition by co.country_id order by count(r.rental_id) desc) as rank
    from country co
    join city ci using (country_id)
    join address a using (city_id)
    join customer c using (address_id)
    join rental r using (customer_id)
    group by co.country, ci.city, co.country_id


)

select country , city , rentals
from city_rentals
where rank=1
order by country;

-- Movie with the highest revenue

select
    f.title as movie_title,
    count(p.payment_id) as total_rentals,
    sum(p.amount) as total_revenue
from film f
         join inventory i on f.film_id = i.film_id
         join rental r on i.inventory_id = r.inventory_id
         join payment p on r.rental_id = p.rental_id
group by f.film_id, f.title
order by total_revenue desc
limit 1;


